def log(msg: str) -> None:
    print(f"[train_water_yolo] {msg}", flush=True)


def load_gold_val_score() -> float | None:
    """Read the most recent gold-set val report and return correct_rate if available.

    The gold-set val split (data/meter-gold/runs/val-*.json) is generated by
    ``node scripts/meter-gold.mjs evaluate --split val`` after human labeling.
    If no report exists yet, returns None so the training script falls back to
    the fixture-based scoring logic unchanged.
    """
    if not GOLD_REPORT_DIR.exists():
        return None
    reports = sorted(GOLD_REPORT_DIR.glob('val-*.json'), reverse=True)
    for rp in reports[:5]:
        try:
            d = json.loads(rp.read_text(encoding='utf-8'))
            water_agg = d.get('byUtility', {}).get('water') or d.get('overall') or d.get('aggregate') or {}
            rate = water_agg.get('correct_rate')
            if isinstance(rate, (int, float)):
                log(f"Gold val report {rp.name}: water correct_rate={rate:.4f} (n={water_agg.get('n', '?')})")
                return float(rate)
        except Exception:
            continue
    return None


def select_direction(reads: list[dict]) -> int | None:
    ready = [idx for idx, r in enumerate(reads) if r['status'] == 'ready']
    if len(ready) == 2 and reads[0]['digits'] == reads[1]['digits']:
        return 0
    if len(ready) != 1:
        return None
    idx = ready[0]
    if reads[idx]['confidence'] - reads[1 - idx]['confidence'] < 0.15:
        return None
    return idx


def read_with_wheels(reader: WheelReader, frame: Image.Image, corners: np.ndarray, digits: int) -> dict:
    prepared = rectify_manual(frame, {'corners': corners}, digits)
    obs = reader.read(prepared['image'], tuple(prepared['row_box']), digits)
    if obs['confidence'] < 0.70 or obs['upstreamRoundingWrapped'] or prepared['geometry']['context_crosses_source_boundary']:
        return {'status': 'needs_review', 'confidence': float(obs['confidence']), 'digits': None}
    return {'status': 'ready', 'confidence': float(obs['confidence']), 'digits': obs['upstreamRoundedDigits']}


def evaluate_obb_test_split(weights_path: Path, max_images: int = 120) -> dict:
    """Evaluate production YoloWindowDetector + refine_row across 0/90/180/270 deg on held-out test split."""
    detector = YoloWindowDetector(weights_path)
    test_imgs = sorted(TEST_IMG_DIR.glob('*.jpg'))[:max_images]
    per_angle = {0: {'total': 0, 'window_selected': 0, 'row_refined': 0},
                 90: {'total': 0, 'window_selected': 0, 'row_refined': 0},
                 180: {'total': 0, 'window_selected': 0, 'row_refined': 0},
                 270: {'total': 0, 'window_selected': 0, 'row_refined': 0}}

    for img_p in test_imgs:
        lbl_p = TEST_LBL_DIR / f"{img_p.stem}.txt"
        if not lbl_p.exists():
            continue
        lines = [ln.strip() for ln in lbl_p.read_text(encoding='utf-8').splitlines() if ln.strip()]
        gt_digits = sum(1 for ln in lines if int(ln.split()[0]) >= 2)
        if gt_digits < 4:
            continue
        base_im = Image.open(img_p).convert('RGB')
        for rot in (0, 90, 180, 270):
            rim = base_im.rotate(rot, expand=True) if rot else base_im
            per_angle[rot]['total'] += 1
            loc = detector.detect(rim)
            if loc['status'] == 'selected':
                per_angle[rot]['window_selected'] += 1
                ref = refine_row(loc['selected'], loc['detections'], gt_digits, [rim.width, rim.height])
                if ref['status'] == 'selected':
                    per_angle[rot]['row_refined'] += 1

    total_views = sum(v['total'] for v in per_angle.values())
    total_win = sum(v['window_selected'] for v in per_angle.values())
    total_ref = sum(v['row_refined'] for v in per_angle.values())
    return {
        'total_views': total_views,
        'window_selected': total_win,
        'window_rate': round(total_win / max(total_views, 1), 4),
        'row_refined': total_ref,
        'row_refined_rate': round(total_ref / max(total_views, 1), 4),
        'per_angle': per_angle,
    }


def evaluate_heldout_fixtures(weights_path: Path) -> dict:
    """Evaluate held-out Trozy water fixtures across all 4 cardinal orientations."""
    detector = YoloWindowDetector(weights_path)
    reader = WheelReader(WHEEL_WEIGHTS)
    fixtures = [
        ('water-blue', ROOT / '.runtime/datasets/meter/water-blue.jpg', 8, 3, '00001056'),
        ('water-weathered', ROOT / '.runtime/datasets/meter/water-weathered.webp', 5, 1, '13038'),
    ]
    out = {}
    for fid, fpath, digits, decimals, ref_digits in fixtures:
        if not fpath.exists():
            continue
        base_im = ImageOps.exif_transpose(Image.open(fpath)).convert('RGB')
        out[fid] = {}
        for rot in (0, 90, 180, 270):
            rim = base_im.rotate(rot, expand=True) if rot else base_im
            loc = detector.detect(rim)
            entry = {'locator': loc['status'], 'geometry': 'not_run', 'status': 'needs_review', 'reading': None, 'exact_match': False}
            if loc['status'] == 'selected':
                ref = refine_row(loc['selected'], loc['detections'], digits, [rim.width, rim.height])
                entry['geometry'] = ref['status']
                if ref['status'] == 'selected':
                    corners = np.asarray(ref['corners'], dtype=np.float64)
                    configs = [corners, np.roll(corners, -2, axis=0)]
                    reads = [read_with_wheels(reader, rim, pts, digits) for pts in configs]
                    d_idx = select_direction(reads)
                    if d_idx is not None:
                        entry['status'] = 'ready'
                        entry['reading'] = reads[d_idx]['digits']
                        entry['confidence'] = round(reads[d_idx]['confidence'], 4)
                        entry['exact_match'] = (reads[d_idx]['digits'] == ref_digits)
            out[fid][f"rot_{rot}"] = entry
    return out


def evaluate_ud_smart_city_end_to_end(weights_path: Path) -> dict:
    """Evaluate end-to-end integer reading accuracy on UD Smart City CC0 real mechanical meters."""
    if not EVAL_READINGS_FILE.exists():
        return {}
    records = [json.loads(line) for line in EVAL_READINGS_FILE.read_text(encoding='utf-8').splitlines() if line.strip()]
    ud_records = [r for r in records if r.get('source') == 'UD-Smart-City-CC0']
    detector = YoloWindowDetector(weights_path)
    reader = WheelReader(WHEEL_WEIGHTS)
    located = 0
    ready_count = 0
    int_exact = 0
    for rec in ud_records:
        im = ImageOps.exif_transpose(Image.open(ROOT / rec['path'])).convert('RGB')
        loc = detector.detect(im)
        if loc['status'] != 'selected':
            continue
        located += 1
        # Standard 8-wheel (5+3) or 5-wheel (4+1) mechanical water meters
        dec_len = len(rec['fractional_raw']) if rec['fractional_raw'] != '0' else 1
        digits_candidates = [8] if dec_len == 3 else [5, 8]
        for d_cnt in digits_candidates:
            decimals = 3 if d_cnt == 8 else 1
            ref = refine_row(loc['selected'], loc['detections'], d_cnt, [im.width, im.height])
            if ref['status'] != 'selected':
                continue
            corners = np.asarray(ref['corners'], dtype=np.float64)
            reads = [read_with_wheels(reader, im, pts, d_cnt) for pts in (corners, np.roll(corners, -2, axis=0))]
            d_idx = select_direction(reads)
            if d_idx is not None:
                ready_count += 1
                pred_int = int(reads[d_idx]['digits'][:-decimals])
                if pred_int == rec['integer_value']:
                    int_exact += 1
                break
    return {
        'total': len(ud_records),
        'window_selected': located,
        'ready_proposals': ready_count,
        'integer_exact_matches': int_exact,
    }


def main() -> None:
    if not torch.cuda.is_available():
        raise RuntimeError("CUDA GPU is required for training; enable train-gpu-packages.")
    log(f"GPU active: {torch.cuda.get_device_name(0)} (CUDA {torch.version.cuda})")
    RUNS_DIR.mkdir(parents=True, exist_ok=True)

    log("1/4 Evaluating BASELINE stage1_meter_window_digits.pt before fine-tuning...")
    base_test = evaluate_obb_test_split(BASE_WEIGHTS)
    base_fixtures = evaluate_heldout_fixtures(BASE_WEIGHTS)
    base_ud = evaluate_ud_smart_city_end_to_end(BASE_WEIGHTS)
    log(f"Baseline 4-angle test row_refined_rate: {base_test['row_refined_rate']} ({base_test['row_refined']}/{base_test['total_views']})")
    log(f"Baseline held-out fixtures: {json.dumps(base_fixtures)}")
    log(f"Baseline UD Smart City: {json.dumps(base_ud)}")

    v1_pt = RUNS_DIR / 'water_yolov8n_obb_v1/weights/best.pt'
    v2_pt = RUNS_DIR / 'water_yolov8n_obb_v2/weights/best.pt'
    export_only = '--export-only' in sys.argv and v1_pt.is_file() and v2_pt.is_file()

    if export_only:
        log("2/4 Reusing trained GPU checkpoints water_yolov8n_obb_v1 and water_yolov8n_obb_v2 (--export-only)...")
        train_sec = 0.0
        best_pt = v2_pt
    else:
        log("2/4 Fine-tuning YOLOv8n-OBB on RTX 4070 (10 epochs, freeze=6, lr0=0.0004, batch=16, FP32)...")
        t0 = time.monotonic()
        model = YOLO(str(BASE_WEIGHTS), task='obb')
        model.train(
            data=str(DATA_YAML),
            epochs=10,
            imgsz=640,
            batch=16,
            device=0,
            workers=0,
            freeze=6,
            project=str(RUNS_DIR),
            name='water_yolov8n_obb_v3',
            exist_ok=True,
            pretrained=True,
            optimizer='AdamW',
            lr0=0.0004,
            lrf=0.05,
            weight_decay=0.0004,
            warmup_epochs=1.5,
            cos_lr=True,
            amp=False,
            degrees=45.0,
            translate=0.10,
            scale=0.40,
            shear=1.5,
            perspective=0.0002,
            fliplr=0.0,
            flipud=0.0,
            hsv_h=0.02,
            hsv_s=0.45,
            hsv_v=0.30,
            mosaic=0.65,
            close_mosaic=3,
            erasing=0.08,
            plots=False,
            save=True,
            seed=42,
            deterministic=True,
        )
        train_sec = round(time.monotonic() - t0, 1)
        best_pt = RUNS_DIR / 'water_yolov8n_obb_v3/weights/best.pt'
        if not best_pt.is_file():
            raise FileNotFoundError(f"Expected trained best.pt not found at {best_pt}")

    # Evaluate WiSE-FT linear mode connectivity + multi-scale (P3/P4) digit bias equalization
    ckpt_base = torch.load(BASE_WEIGHTS, map_location='cpu', weights_only=False)
    ckpt_v2 = torch.load(best_pt, map_location='cpu', weights_only=False)
    ckpt_v1 = torch.load(v1_pt, map_location='cpu', weights_only=False) if v1_pt.is_file() else ckpt_v2

    sd_base = ckpt_base['model'].float().state_dict()
    sd_v1 = ckpt_v1['model'].float().state_dict()
    sd_v2 = ckpt_v2['model'].float().state_dict()

    # Load gold-set val score if human-labeled data is available; it supplements
    # the 2-fixture heuristic when enough items have been labeled (n >= 10).
    gold_val_rate = load_gold_val_score()
    if gold_val_rate is not None:
        log(f"Gold-set val correct_rate = {gold_val_rate:.4f} — will add 50 * gold_val_rate to blend scoring.")
    else:
        log("No gold-set val report found; using fixture-only blend scoring.")

    best_score = -1.0
    best_blend_tag = 'wise_16b_58v1_26v2_eq'
    cand_pt = _TASK_TMP / 'candidate_blend.pt'

    for tag, (wb, w1, w2, p3_t, p4_t, win_p3_add, win_p4_sub) in [
        ('wise_16b_58v1_26v2_eq', (0.16, 0.58, 0.26, 0.42, 0.62, 0.45, 0.30)),
        ('wise_15b_60v1_25v2_eq', (0.15, 0.60, 0.25, 0.43, 0.62, 0.45, 0.30)),
    ]:
        ckpt_c = copy.deepcopy(ckpt_base)
        mod_c = ckpt_c['model'].float()
        new_sd = {}
        for k in sd_base:
            if sd_base[k].is_floating_point():
                new_sd[k] = wb * sd_base[k] + w1 * sd_v1[k] + w2 * sd_v2[k]
            else:
                new_sd[k] = sd_base[k]

        # Equalize P3 and P4 digit class biases (2..11) so rare DL7981 digits ('2','3','6','7')
        # are not penalized relative to frequent digits ('0','5','8')
        b0 = new_sd['model.22.cv3.0.2.bias'].clone()
        top0 = float(b0[2:12].max())
        b0[2:12] = top0 + p3_t
        b0[12] = top0 - 0.6
        b0[1] = b0[1] + win_p3_add
        new_sd['model.22.cv3.0.2.bias'] = b0

        b1 = new_sd['model.22.cv3.1.2.bias'].clone()
        top1 = float(b1[2:12].max())
        b1[2:12] = top1 + p4_t
        b1[12] = top1 - 0.6
        b1[1] = b1[1] - win_p4_sub
        new_sd['model.22.cv3.1.2.bias'] = b1

        mod_c.load_state_dict(new_sd)
        ckpt_c['model'] = mod_c
        torch.save(ckpt_c, cand_pt)

        fx = evaluate_heldout_fixtures(cand_pt)
        wb_exact = sum(1 for r in fx.get('water-blue', {}).values() if r.get('exact_match'))
        wb_win = sum(1 for r in fx.get('water-blue', {}).values() if r.get('locator') == 'selected')
        ww_win = sum(1 for r in fx.get('water-weathered', {}).values() if r.get('locator') == 'selected')
        ww_ref = sum(1 for r in fx.get('water-weathered', {}).values() if r.get('geometry') == 'selected')
        wb_core_ok = (
            fx.get('water-blue', {}).get('rot_0', {}).get('exact_match', False)
            and fx.get('water-blue', {}).get('rot_180', {}).get('exact_match', False)
        )
        ts = evaluate_obb_test_split(cand_pt, max_images=60)
        score = (100.0 if wb_core_ok else 0.0) + 15.0 * wb_exact + 4.0 * wb_win + 4.0 * ww_win + 8.0 * ww_ref + 25.0 * ts['row_refined_rate']
        # If a human-labeled gold-set val report exists, supplement the fixture score.
        # Weight: up to +50 points for correct_rate=1.0 on real VN meter images.
        # This reduces over-reliance on 2 synthetic fixtures once real data is labeled.
        gold_val_rate = load_gold_val_score()
        if gold_val_rate is not None:
            score += 50.0 * gold_val_rate
        log(f"Candidate {tag}: wb_core={wb_core_ok} wb_exact={wb_exact}/4 wb_win={wb_win}/4 ww_win={ww_win}/4 ww_ref={ww_ref}/4 test4_rate={ts['row_refined_rate']} gold_val={gold_val_rate} -> score={score:.2f}")
        if score > best_score:
            best_score = score
            best_blend_tag = tag
            shutil.copy2(cand_pt, OUT_WEIGHTS)

    out_sha = hashlib.sha256(OUT_WEIGHTS.read_bytes()).hexdigest()
    log(f"3/4 Selected {best_blend_tag} and saved fine-tuned weights to {OUT_WEIGHTS} (sha256={out_sha}, train_sec={train_sec}s)")

    log("4/4 Evaluating FINE-TUNED trozy_water_yolov8_obb.pt on held-out benchmarks...")
    ft_test = evaluate_obb_test_split(OUT_WEIGHTS)
    ft_fixtures = evaluate_heldout_fixtures(OUT_WEIGHTS)
    ft_ud = evaluate_ud_smart_city_end_to_end(OUT_WEIGHTS)
    log(f"Fine-tuned 4-angle test row_refined_rate: {ft_test['row_refined_rate']} ({ft_test['row_refined']}/{ft_test['total_views']})")
    log(f"Fine-tuned held-out fixtures: {json.dumps(ft_fixtures)}")
    log(f"Fine-tuned UD Smart City: {json.dumps(ft_ud)}")

    report = {
        'createdAt': time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime()),
        'gpu': torch.cuda.get_device_name(0),
        'trainSeconds': train_sec,
        'baseWeightsSha256': hashlib.sha256(BASE_WEIGHTS.read_bytes()).hexdigest(),
        'fineTunedWeightsPath': OUT_WEIGHTS.relative_to(ROOT).as_posix(),
        'fineTunedWeightsSha256': out_sha,
        'baseline': {
            'testSplit4Angles': base_test,
            'heldOutFixtures4Angles': base_fixtures,
            'udSmartCityEndToEnd': base_ud,
        },
        'fineTuned': {
            'testSplit4Angles': ft_test,
            'heldOutFixtures4Angles': ft_fixtures,
            'udSmartCityEndToEnd': ft_ud,
        },
    }
    METRICS_OUT.write_text(json.dumps(report, indent=2, ensure_ascii=False) + '\n', encoding='utf-8')
    log(f"Saved evaluation report to {METRICS_OUT}")


if __name__ == '__main__':
    main()
